import { expect, test } from "@playwright/test";
import { renderFormFixture } from "./fixtures/form-browser";
let html: string;
test.beforeAll(async () => { html = await renderFormFixture("e2e/fixtures/client-purchases.tsx"); });
for (const width of [320, 768, 1440]) test(`client purchases filters, totals and pagination at ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 });
  await page.route("https://forms.test/**", route => route.fulfill({ contentType: "text/html", body: html }));
  await page.goto("https://forms.test/dashboard/reports/clients?page=2");
  await expect(page.locator("#client-purchases-table")).toContainText("Premium treatment");
  await expect(page.locator("#client-purchases-table")).toContainText("1.5 bottle");
  await expect(page.locator("#client-purchases-table")).toContainText("Promo inclusion");
  await expect(page.locator("#client-purchases-table")).toContainText("Jamie Cruz");
  await expect(page.locator("#client-purchases-table")).toContainText("Taylor Santos");
  await expect(page.locator("#client-purchases-totals")).toContainText("1,500.00");
  await page.locator("#client-purchases-filters-search-toggle").click();
  await page.locator("#client-purchases-client-search").fill("Alex");
  await page.locator("#client-purchases-filters-filters-button").click();
  await page.locator("#client-purchases-period").selectOption("custom");
  await page.locator("#client-purchases-start").fill("2026-10-02");
  await page.locator("#client-purchases-end").fill("2026-10-12");
  await page.locator("#client-purchases-kind").selectOption("product");
  await page.locator("#client-purchases-item-search").fill("Care oil");
  await page.locator("#client-purchases-apply").click();
  await expect(page.locator("#client-purchases-scope")).toContainText("2026-10-02 – 2026-10-12");
  const query = new URL(page.url()).searchParams;
  expect(query.get("q")).toBe("Alex"); expect(query.get("item")).toBe("Care oil"); expect(query.has("page")).toBe(false);
  await expect(page.locator("#client-purchases-next")).toHaveAttribute("href", /kind=product.*page=2/);
  await page.locator("#client-purchases-next").click();
  await expect(page.locator("#client-purchases-pagination")).toContainText("Page 2 of 2");
  await expect(page.locator("#client-purchases-previous")).toHaveAttribute("href", /q=Alex/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath(`client-purchases-${width}.png`), fullPage: true });
  await page.goto("https://forms.test/dashboard/reports/clients?unassigned=1");
  await expect(page.locator("#client-purchases-table")).toContainText("Not recorded");
  await page.goto("https://forms.test/dashboard/reports/clients?empty=1");
  await expect(page.locator("#client-purchases-table-empty")).toHaveText("No client purchases match these filters.");
  await expect(page.locator("#client-purchases-next")).toHaveCount(0);
});
